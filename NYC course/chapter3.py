#integers : 0 to infinity and -1 to negative infinity
a = -4
b = 235

print(a)
print(b)


print(type(a))
print(type(b))

#float : values with decimal points and in the form p/q where p and q are integers and q is not zero
pi = 3.14
x = 6/3
print(pi)
print(x)
print(type(pi))
print(type(x))

#complex numbers : numbers in the form a + bj where a and b are real numbers and j is the imaginary unit
z = 2 + 3j
print(z)
print(type(z))

#strings : used to store anything that you can type, we can use either single or double quotes
random_shit = "534"
name = "Alice"
x = 'yo bro he said "you are a bad person"'
print(name)
print(random_shit)
print(x)
print(type(name))
print(type(random_shit))
print(type(x))

#boolean : used to represent the truth values True and False (T and F are always capitalized)
is_true = True
is_false = False
print(is_true)
print(is_false)
print(type(is_true))
print(type(is_false))